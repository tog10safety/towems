"""Vehicle movement log as a PDF.

The plan (trip, itinerary, road route) already has its own documents. This is
the *execution* record: each vehicle's ETD beside its ATD, every stop's planned
time beside the time a person recorded, the variance, and who recorded it. It is
the artefact a safety officer or an inspector reads after the mission, so it
prints what happened and never what was merely expected.
"""

from __future__ import annotations

from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

PAGE_WIDTH, PAGE_HEIGHT = landscape(A4)

INK = colors.HexColor("#1f2328")
MUTED = colors.HexColor("#5b6570")
RULE = colors.HexColor("#c9d1d9")
LATE = colors.HexColor("#8b1a1a")
HEADER_FILL = colors.HexColor("#eef2f6")

#: Minutes behind plan before a row is called out in red. Mirrors the alerting
#: threshold in ``apps.ops.tracking`` so the PDF and the notifications agree.
GRACE_MINUTES = 15


def _pdf_datetime(value):
    from apps.core import timeutils

    return timeutils.format_datetime(value) if value else "—"


def _stamp():
    from apps.core import timeutils

    return timeutils.format_datetime(timeutils.now())


def _variance(actual, planned):
    """Whole minutes ``actual`` is after ``planned`` (negative = early)."""
    if actual is None or planned is None:
        return None
    return int(round((actual - planned).total_seconds() / 60))


def _variance_text(minutes):
    if minutes is None:
        return "—"
    if minutes == 0:
        return "on time"
    return f"{minutes:+d} min"


def _styles():
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "toms-title",
            parent=base["Title"],
            fontName="Helvetica-Bold",
            fontSize=17,
            leading=21,
            alignment=0,
            textColor=INK,
            spaceAfter=2,
        ),
        "subtitle": ParagraphStyle(
            "toms-subtitle",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=13,
            textColor=MUTED,
        ),
        "vehicle": ParagraphStyle(
            "toms-vehicle",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=11.5,
            leading=15,
            textColor=INK,
            spaceBefore=6,
            spaceAfter=3,
        ),
        "body": ParagraphStyle(
            "toms-body",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11.5,
            textColor=INK,
        ),
        "cell": ParagraphStyle(
            "toms-cell",
            parent=base["Normal"],
            fontName="Helvetica",
            fontSize=7.8,
            leading=10,
            textColor=INK,
        ),
        "cell_bold": ParagraphStyle(
            "toms-cell-bold",
            parent=base["Normal"],
            fontName="Helvetica-Bold",
            fontSize=7.8,
            leading=10,
            textColor=INK,
        ),
        "note": ParagraphStyle(
            "toms-note",
            parent=base["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=8,
            leading=11,
            textColor=MUTED,
        ),
    }


def _footer(canvas, doc):
    from apps.core import timeutils

    canvas.saveState()
    canvas.setStrokeColor(RULE)
    canvas.setLineWidth(0.5)
    canvas.line(12 * mm, 12 * mm, PAGE_WIDTH - 12 * mm, 12 * mm)
    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(12 * mm, 8 * mm, f"Generated by TOWEMS · {_stamp()}")
    canvas.drawRightString(
        PAGE_WIDTH - 12 * mm,
        8 * mm,
        f"Page {doc.page} · Movement log · {timeutils.format_date(timeutils.today())}",
    )
    canvas.restoreState()


def _table(header, rows, widths, *, styles):
    data = [[Paragraph(cell, styles["cell_bold"]) for cell in header]]
    for row in rows:
        data.append(
            [
                cell if hasattr(cell, "wrap") else Paragraph(str(cell), styles["cell"])
                for cell in row
            ]
        )
    table = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("GRID", (0, 0), (-1, -1), 0.4, RULE),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]
    table.setStyle(TableStyle(style))
    return table


def _run_block(run, mission, *, styles):
    """Everything the log says about one vehicle, kept on one page if possible."""
    from apps.ops import tracking
    from apps.ops.models import MovementEvent

    story = []
    heading = run.vehicle.registration_number or f"Vehicle {run.vehicle_id}"
    extras = [run.vehicle.vehicle_type, run.driver.full_name if run.driver_id else "No driver"]
    if run.is_lead:
        extras.append("Convoy lead")
    story.append(
        Paragraph(
            f"{heading} — {run.trip.trip_number} ({run.get_status_display()})",
            styles["vehicle"],
        )
    )
    story.append(
        Paragraph(
            " · ".join([part for part in extras if part]),
            styles["subtitle"],
        )
    )
    story.append(Spacer(1, 3))

    departure_late = _variance(run.atd, run.etd)
    summary = [
        ["ETD (planned)", _pdf_datetime(run.etd)],
        [
            "ATD (actual)",
            f"{_pdf_datetime(run.atd)}"
            + (f" · {run.get_atd_source_display()}" if run.atd_source else ""),
        ],
        ["Departure variance", _variance_text(departure_late)],
        ["Completed", _pdf_datetime(run.completed_at)],
        ["Reported positions", str(run.pings.count())],
        [
            "Last position",
            f"{_pdf_datetime(run.last_ping_at)}"
            + (
                f" · ±{round(run.last_accuracy_m)} m"
                if run.last_accuracy_m is not None
                else ""
            ),
        ],
    ]
    summary_table = Table(
        [
            [Paragraph(left, styles["cell_bold"]), Paragraph(right, styles["cell"])]
            for left, right in summary
        ],
        colWidths=[42 * mm, 108 * mm],
    )
    summary_table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.4, RULE),
                ("BACKGROUND", (0, 0), (0, -1), HEADER_FILL),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    story.append(summary_table)
    story.append(Spacer(1, 6))

    state = tracking._run_stop_state(run)
    stop_rows = []
    for index, row in enumerate(state, start=1):
        stop = row["stop"]
        arrival_late = _variance(row["arrived_at"], stop.planned_arrival)
        departure_late = _variance(row["departed_at"], stop.planned_departure)
        status = (
            "Departed"
            if row["departed_at"]
            else "Arrived"
            if row["arrived_at"]
            else "Pending"
        )
        stop_rows.append(
            [
                str(stop.sequence),
                Paragraph(stop.location_name or "—", styles["cell"]),
                _pdf_datetime(stop.planned_arrival),
                _pdf_datetime(row["arrived_at"]),
                _variance_text(arrival_late),
                _pdf_datetime(row["departed_at"]),
                _variance_text(departure_late),
                status,
            ]
        )

    if stop_rows:
        story.append(Paragraph("Itinerary — planned against actual", styles["cell_bold"]))
        story.append(
            _table(
                [
                    "#",
                    "Stop",
                    "Planned arrival",
                    "Actual arrival",
                    "Δ",
                    "Departure",
                    "Δ",
                    "Status",
                ],
                stop_rows,
                [8 * mm, 58 * mm, 38 * mm, 38 * mm, 16 * mm, 38 * mm, 16 * mm, 22 * mm],
                styles=styles,
            )
        )
        story.append(Spacer(1, 6))

    events = list(run.events.select_related("stop", "recorded_by").order_by("actual_at", "id"))
    if events:
        event_rows = []
        for event in events:
            late = _variance(event.actual_at, event.planned_at)
            event_rows.append(
                [
                    _pdf_datetime(event.actual_at),
                    Paragraph(event.get_kind_display(), styles["cell"]),
                    Paragraph(
                        f"{event.stop.sequence}. {event.stop.location_name}"
                        if event.stop_id
                        else "—",
                        styles["cell"],
                    ),
                    _pdf_datetime(event.planned_at),
                    _variance_text(late),
                    Paragraph(event.get_source_display(), styles["cell"]),
                    Paragraph(
                        event.recorded_by.full_name if event.recorded_by_id else "—",
                        styles["cell"],
                    ),
                    Paragraph(event.note or "", styles["cell"]),
                ]
            )
        story.append(Paragraph("Recorded events (append-only)", styles["cell_bold"]))
        story.append(
            _table(
                [
                    "Actual time",
                    "Event",
                    "Stop",
                    "Planned",
                    "Δ",
                    "Source",
                    "Recorded by",
                    "Note",
                ],
                event_rows,
                [30 * mm, 26 * mm, 40 * mm, 30 * mm, 15 * mm, 26 * mm, 34 * mm, 69 * mm],
                styles=styles,
            )
        )
    else:
        story.append(
            Paragraph("No movement event has been recorded for this vehicle.", styles["note"])
        )

    if run.notes:
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"Notes: {run.notes}", styles["note"]))

    story.append(Spacer(1, 8))
    return story


def generate_movement_log_pdf(mission) -> bytes:
    """Render every vehicle run of ``mission`` as one movement-log PDF."""
    from apps.core import timeutils

    styles = _styles()
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=(PAGE_WIDTH, PAGE_HEIGHT),
        leftMargin=12 * mm,
        rightMargin=12 * mm,
        topMargin=12 * mm,
        bottomMargin=18 * mm,
        title=f"Movement log {mission.mission_number}",
        author="TOWEMS",
    )

    unit = mission.unit
    story = [
        Paragraph("VEHICLE MOVEMENT LOG", styles["title"]),
        Paragraph(
            f"{mission.mission_number} · {mission.title}",
            styles["subtitle"],
        ),
        Paragraph(
            " · ".join(
                [
                    unit.name if unit else "No unit recorded",
                    mission.get_category_display(),
                    f"Status: {mission.get_status_display()}",
                ]
            ),
            styles["subtitle"],
        ),
        Paragraph(
            "Planned "
            f"{_pdf_datetime(mission.start_at)} – {_pdf_datetime(mission.end_at)}"
            f" · Dispatched {_pdf_datetime(mission.dispatched_at)}"
            f" · Closed {_pdf_datetime(mission.completed_at)}",
            styles["subtitle"],
        ),
        Paragraph(
            f"Printed {_stamp()}. A row counts as late only past "
            f"{GRACE_MINUTES} min; every actual time below was recorded by a person, "
            "not inferred from a GPS breadcrumb.",
            styles["note"],
        ),
        Spacer(1, 8),
    ]

    runs = list(
        mission.vehicle_runs.select_related("vehicle", "driver", "trip")
        .prefetch_related("events__stop", "events__recorded_by", "trip__itinerary")
        .order_by("vehicle__registration_number", "id")
    )
    if not runs:
        story.append(
            Paragraph(
                "No movement tracking has been opened for this mission.",
                styles["body"],
            )
        )
    else:
        for index, run in enumerate(runs):
            block = _run_block(run, mission, styles=styles)
            if index:
                story.append(PageBreak())
            story.extend(block)

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()


def can_view_movement_log(user, mission, *, is_driver: bool = False) -> bool:
    """Monitoring roles, the Operations Center, and the vehicle's own driver."""
    from apps.ops import tracking

    return bool(
        is_driver
        or tracking.can_manage(user, mission)
        or tracking.can_monitor(user, mission)
    )
